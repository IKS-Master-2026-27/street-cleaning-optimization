"""Generate 8-hour variants of the real-city instances.

Real working shifts last 8 hours, but most real instances allow far more time per
vehicle (up to ~227 h). This script copies each real instance with the time limit
T (third number of the header, seconds per vehicle) capped at 8 h = 28,800 s;
everything else (network, streets, fleet, depot, alpha) is unchanged.

    python scripts/make_8h_instances.py

Output: data/input/real_instances_8h/<City>/instance.txt (generated, not committed).

Sydney is skipped: 163 of its mandatory streets need more than 8 h just to drive
depot -> street -> depot, so no valid solution can exist with T = 8 h.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/input/real_instances"
TARGET = ROOT / "data/input/real_instances_8h"
EIGHT_HOURS = 8 * 3600
SKIP = {"Sydney"}  # infeasible with T = 8 h (mandatory streets out of reach)


def main() -> int:
    TARGET.mkdir(parents=True, exist_ok=True)
    (TARGET / ".gitignore").write_text("# generated by scripts/make_8h_instances.py\n*\n!.gitignore\n",
                                       encoding="utf-8")
    for path in sorted(SOURCE.glob("*/instance.txt")):
        city = path.parent.name
        if city in SKIP:
            print(f"{city}: skipped (mandatory streets unreachable within 8 h)")
            continue
        with open(path, encoding="utf-8") as source:
            header = source.readline().split()
            rest = source.read()
        old = int(header[2])
        header[2] = str(min(old, EIGHT_HOURS))
        out = TARGET / city / "instance.txt"
        out.parent.mkdir(parents=True, exist_ok=True)
        with open(out, "w", encoding="utf-8", newline="\n") as target:
            target.write(" ".join(header) + "\n" + rest)
        print(f"{city}: T {old} s ({old / 3600:.1f} h) -> {header[2]} s -> {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
